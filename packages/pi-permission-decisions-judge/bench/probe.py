#!/usr/bin/env python3
"""Reusable probe for a llama.cpp decision endpoint (/v1/systemone).

One script, many models/builds. Every case is recorded as structured JSON; the same run
also renders Markdown tables for humans. Designed so runs against different models or
llama.cpp builds can be diffed with report.py.

  python3 probe.py --label d3-mini                      # the core suite
  python3 probe.py --label d3-mini --envelope           # + crash/ceiling envelope (kills the server)
  python3 probe.py --label d3-mini --suite core,concurrency
  python3 probe.py --label d3-mini --only multiseq      # one case, fast

Safety: the b11606/vllm-d3-flash server *dies* (not 500s) when a per-question prompt is
too large with >=2 questions. Cases that would exceed --max-per-question-tokens are skipped
unless --envelope asks for them. Transport errors are recorded as crash events with the
observed reload time, and the run continues once /health is back.
"""
