def noul(key):
    return {"type": "noul", "instructions": CONCERNS[key], "criteria": CRITERIA[key]}


def gate_questions(keys=("intent", "reversible", "blast_radius", "credential")):
    return {k: noul(k) for k in keys}


def generic(n):
    return {f"q{i}": {"type": "noul", "instructions": f"is condition {i} satisfied?"} for i in range(n)}


# ---------------------------------------------------------------- endpoint client
class Endpoint:
    def __init__(self, base, timeout=300, recover_s=300, log=print):
        self.base, self.timeout, self.recover_s, self.log = base.rstrip("/"), timeout, recover_s, log
        self.crashes = []
        self.dead = False

    def get(self, path, timeout=15):
        try:
            with urllib.request.urlopen(self.base + path, timeout=timeout) as r:
                return r.status, json.loads(r.read())
        except urllib.error.HTTPError as e:
            return e.code, e.read().decode()[:300]
        except Exception as e:
            return None, f"{type(e).__name__}: {e}"

    def health(self):
        st, _ = self.get("/health", timeout=5)
        return st == 200

    def wait_up(self, max_s=None):
        max_s = max_s or self.recover_s
        t0 = time.time()
        while time.time() - t0 < max_s:
            if self.health():
                return time.time() - t0
            time.sleep(3)
        return None

    def call(self, payload, path="/v1/systemone"):
        """-> dict(body|None, latency, error, kind) kind in ok|http|crash"""
        req = urllib.request.Request(self.base + path, data=json.dumps(payload).encode(),
                                     headers={"content-type": "application/json"})
        t0 = time.perf_counter()
        try:
            with urllib.request.urlopen(req, timeout=self.timeout) as r:
                return {"body": json.loads(r.read()), "latency": time.perf_counter() - t0,
                        "error": None, "kind": "ok"}
        except urllib.error.HTTPError as e:
            return {"body": None, "latency": time.perf_counter() - t0,
                    "error": e.read().decode()[:300], "kind": "http"}
        except Exception as e:
            msg = f"{type(e).__name__}: {e}"
            out = {"body": None, "latency": time.perf_counter() - t0, "error": msg, "kind": "crash"}
            if not self.health():  # the process died, not a request error
                up = self.wait_up()
                out["recovered_in"] = up
                self.crashes.append({"at": datetime.datetime.now().isoformat(timespec="seconds"),
                                     "error": msg, "recovered_in": up})
                if up is None:
                    self.dead = True
                    self.log("    !! endpoint died and did not come back - stopping the run")
                else:
                    self.log(f"    !! endpoint died ({msg[:60]}), back after {round(up)}s")
            else:
                out["kind"] = "http"
            return out

    def parallel(self, payloads):
        import concurrent.futures as cf
        t0 = time.perf_counter()
        with cf.ThreadPoolExecutor(max_workers=min(len(payloads), 8)) as ex:
            fs = [ex.submit(self.call, p) for p in payloads]
            out = [f.result() for f in fs]
        for o in out:
            o["wall"] = time.perf_counter() - t0
        return out


# ---------------------------------------------------------------- helpers
def est_tokens(*parts):
    """Cheap pre-check only; the real number is usage.input_tokens from the response."""
    return sum(len(str(p)) for p in parts) // 4


def med(v):
    return round(statistics.median(v), 4) if v else None


def summarize(runs):
    ok = [r for r in runs if r["kind"] == "ok"]
    return {
        "n": len(runs), "n_ok": len(ok), "n_crash": sum(1 for r in runs if r["kind"] == "crash"),
        "median_latency": med([r["latency"] for r in ok]),
        "min_latency": round(min([r["latency"] for r in ok]), 4) if ok else None,
        "max_latency": round(max([r["latency"] for r in ok]), 4) if ok else None,
        "input_tokens": ok[0]["input_tokens"] if ok else None,
        "answers": ok[0]["answers"] if ok else None,
        "errors": sorted({(r["error"] or "")[:120] for r in runs if r["kind"] != "ok"}),
    }


def timed(ep, payload, reps):
    runs = []
    for _ in range(reps):
        r = ep.call(payload)
        if r["kind"] == "ok":
            r["input_tokens"] = r["body"]["usage"]["input_tokens"]
            r["answers"] = {k: (round(v["noul"], 4) if v.get("type") == "noul" else
                                {kk: (round(vv, 4) if isinstance(vv, float) else vv)
                                 for kk, vv in v.items() if kk in ("choice", "score", "confidence")})
                            for k, v in r["body"]["answers"].items()}
        runs.append(r)
    return runs


