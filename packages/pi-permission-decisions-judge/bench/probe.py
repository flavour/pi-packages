def to_md(meta, records):
    out = [f"# probe — {meta['label']}", "",
           f"- run: `{meta['started']}`  url `{meta['url']}`  text version `{meta['text_version']}`",
           f"- machine: {meta.get('machine') or '?'}",
           f"- stack: {meta.get('stack') or '?'}  revision: `{meta.get('revision') or '?'}`",
           f"- notes: {meta.get('notes') or '-'}",
           f"- model: `{meta['identity'].get('model')}`  build `{meta['identity'].get('build_info')}`  "
           f"slots `{meta['identity'].get('n_slots')}`  n_ctx `{meta['identity'].get('n_ctx')}`",
           f"- reps: {meta['reps']}  max per-question tokens: {meta['max_per_question_tokens']}  "
           f"crashes during run: **{len(meta['crashes'])}**", ""]
    groups = {}
    for r in records:
        groups.setdefault(r["case"], []).append(r)
    for case, rows in groups.items():
        out.append(f"## {case}")
        keys = [k for k in ("params", "median", "min", "max", "wall", "input_tokens", "tokens_per_question",
                            "ms_per_question", "ms_per_extra_question", "readings", "band", "answers",
                            "abs_delta", "max_delta", "spread", "distinct", "sets", "kind", "skipped",
                            "errors", "error", "recovered_in", "status", "model", "build_info",
                            "n_slots", "n_ctx", "state_tokens_est", "tok_1q", "ms_1q", "tok_4q", "ms_4q",
                            "pads", "tokens_per_question", "latency", "per_request", "total_tokens",
                            "prompt_tokens", "processed_tokens", "cached_tokens", "inherited_tokens",
                            "computed_tokens", "n_slot_tasks", "n_inheriting", "prefix_tokens",
                            "reported_input_tokens", "compute_saved_pct", "verdict", "latency_ratio",
                            "from", "to", "body")
                if any(k in r for r in rows)]
        out.append("| " + " | ".join(keys) + " |")
        out.append("|" + "---|" * len(keys))
        for r in rows:
            cells = []
            for k in keys:
                v = r.get(k, "")
                if k == "params":
                    v = json.dumps(v, sort_keys=True)
                elif isinstance(v, (dict, list)):
                    v = json.dumps(v, sort_keys=True)
                cells.append(str(v).replace("|", "\\|")[:160])
            out.append("| " + " | ".join(cells) + " |")
        out.append("")
    if meta["crashes"]:
        out.append("## crashes")
        for c in meta["crashes"]:
            out.append(f"- `{c['at']}` {c['error'][:100]} — back after {c['recovered_in']}")
    return "\n".join(out)


