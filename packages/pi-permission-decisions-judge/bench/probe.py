def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--url", default="http://jetson:9931")
    ap.add_argument("--label", required=True, help="run label, e.g. d3-mini or d3-flash-b11612")
    ap.add_argument("--reps", type=int, default=5, help="reps for the latency-vs-n case")
    ap.add_argument("--suite", default="core", help="comma list: core,concurrency,envelope")
    ap.add_argument("--only", default=None, help="run only these case functions, e.g. multiseq,realistic")
    ap.add_argument("--max-per-question-tokens", type=int, default=200,
                    help="skip cases whose estimated per-question prompt exceeds this (envelope ignores it)")
    ap.add_argument("--recover-s", type=int, default=300, help="how long to wait for an endpoint that died")
    ap.add_argument("--destructive", action="store_true", help="allow cases that can kill the endpoint")
    ap.add_argument("--merge-total", type=int, default=700,
                    help="target prompt tokens per question for the merge case (compare against n_ubatch)")
    ap.add_argument("--ceiling-pads", default="20,30,40,44,46,50,60,80",
                    help="comma list of PAD repeats for the ceiling sweep (~10 tokens each)")
    ap.add_argument("--env-pads", default="10,14,16,20,25,30,40,50,60",
                    help="comma list of PAD repeats for the envelope ramp (~10 tokens each)")
    ap.add_argument("--share-max-n", type=int, default=8,
                    help="largest question count in the sharing case (set it to the server's --parallel)")
    ap.add_argument("--out-dir", default=os.path.join(os.path.dirname(os.path.abspath(__file__)), "results"))
    ap.add_argument("--machine", default="", help="hardware the server runs on, e.g. 'Jetson Orin NX 16GB, JetPack 7.2.1'")
    ap.add_argument("--stack", default="", help="software stack, e.g. 'llama.cpp server (llama-server)'")
    ap.add_argument("--revision", default="", help="VCS revision of the stack the server was built from")
    ap.add_argument("--expect-model", default="", help="refuse to run if the server is not answering with this model")
    ap.add_argument("--allow-identity-mismatch", action="store_true",
                    help="warn instead of failing when --revision / --expect-model disagree with the server")
    ap.add_argument("--expect-slots", type=int, default=0,
                    help="refuse to run if /slots does not report this many slots (server --parallel)")
    ap.add_argument("--expect-ctx-slot", type=int, default=0,
                    help="refuse to run if /slots does not report this n_ctx per slot (-c / --parallel)")
    ap.add_argument("--expect-ubatch", type=int, default=0,
                    help="cross-check the ceiling case's reported n_ubatch against this")
    ap.add_argument("--notes", default="", help="free-text run notes (server flags, quantization, etc.)")
    ap.add_argument("--quiet", action="store_true")
    cfg = ap.parse_args()
    cfg.ceiling_pads = tuple(int(x) for x in cfg.ceiling_pads.split(",") if x.strip())
    cfg.env_pads = tuple(int(x) for x in cfg.env_pads.split(",") if x.strip())

    log = (lambda *a: None) if cfg.quiet else (lambda *a: print(*a, flush=True))
    ep = Endpoint(cfg.url, log=log, recover_s=cfg.recover_s)
    st, models = ep.get("/v1/models")
    if st != 200:
        print(f"endpoint not answering at {cfg.url}: {st} {models}"); sys.exit(1)
    _, props = ep.get("/props")
    _, slots = ep.get("/slots")
    slot_list = slots if isinstance(slots, list) else []
    identity = {
        "model": (models.get("data", [{}])[0].get("id") if isinstance(models, dict) else None),
        "build_info": props.get("build_info") if isinstance(props, dict) else None,
        "n_ctx": (props.get("n_ctx") if isinstance(props, dict) and props.get("n_ctx")
                  else (slot_list[0].get("n_ctx") if slot_list else None)),
        "n_ctx_slot": slot_list[0].get("n_ctx") if slot_list else None,
        "n_slots": len(slot_list) if slot_list else None,
        "model_path": props.get("model_path") if isinstance(props, dict) else None,
    }
    log(f"model={identity['model']} build={identity['build_info']} slots={identity['n_slots']} "
        f"n_ctx/slot={identity['n_ctx_slot']}")

    # provenance: the numbers are only comparable if the model and build are what we claim.
    # llama.cpp build_info is "b<rev-list count>-<9-char sha>", so the sha suffix must match --revision.
    check = {"model_expected": cfg.expect_model or None, "model_ok": True,
             "revision_expected": cfg.revision or None, "revision_ok": True,
             "slots_expected": cfg.expect_slots or None, "slots_ok": True,
             "ctx_slot_expected": cfg.expect_ctx_slot or None, "ctx_slot_ok": True,
             "ubatch_expected": cfg.expect_ubatch or None, "ubatch_ok": None}
    if cfg.expect_model and identity["model"] != cfg.expect_model:
        check["model_ok"] = False
        log(f"!! model mismatch: server says {identity['model']!r}, expected {cfg.expect_model!r}")
    if cfg.revision and identity.get("build_info"):
        sha = str(identity["build_info"]).split("-")[-1][:9]
        check["revision_ok"] = sha == cfg.revision[:9]
        if not check["revision_ok"]:
            log(f"!! revision mismatch: build_info {identity['build_info']} -> {sha}, expected {cfg.revision[:9]}")
        else:
            log(f"   revision check ok: {identity['build_info']}")
    if cfg.expect_slots and identity["n_slots"] != cfg.expect_slots:
        check["slots_ok"] = False
        log(f"!! slot mismatch: server has {identity['n_slots']} slots, expected {cfg.expect_slots} "
            f"(server --parallel {cfg.expect_slots})")
    # -c is divided across the slots, so the same -c means different things at different --parallel:
    # a run recorded as "-c 65536 (16384/slot)" on a server actually running 8192/slot is a lie.
    if cfg.expect_ctx_slot and identity["n_ctx_slot"] != cfg.expect_ctx_slot:
        check["ctx_slot_ok"] = False
        log(f"!! n_ctx/slot mismatch: server has {identity['n_ctx_slot']}, expected {cfg.expect_ctx_slot} "
            f"(-c {cfg.expect_ctx_slot * (cfg.expect_slots or 1)})")
    if (not check["model_ok"] or not check["revision_ok"] or not check["slots_ok"]
            or not check["ctx_slot_ok"]) and not cfg.allow_identity_mismatch:
        print("refusing to record a run under the wrong provenance "
              "(pass --allow-identity-mismatch to record it anyway)")
        sys.exit(2)

    if cfg.only:  # --only searches every suite, so you don't also need --suite
        want = {x.strip() for x in cfg.only.split(",")}
        fns = [f for f in sum(SUITES.values(), []) if f.__name__[2:] in want]
    else:
        fns = []
        for name in cfg.suite.split(","):
            fns += SUITES.get(name.strip(), [])

    started = datetime.datetime.now().isoformat(timespec="seconds")
    records = []
    for fn in fns:
        log(f"== {fn.__name__[2:]}")
        try:
            rows = fn(ep, cfg)
        except Exception as e:
            rows = [{"case": fn.__name__[2:], "params": {}, "errors": [f"harness exception: {e}"]}]
        records += rows
        for r in rows:
            log("   ", json.dumps({k: v for k, v in r.items() if k != "body"})[:180])
        if ep.dead:
            log("   endpoint is gone; stopping the run")
            break

    # the ceiling case reports n_ubatch in its 500 body; cross-check it against --expect-ubatch so a
    # run cannot be recorded under a batch config it did not actually run with.
    if cfg.expect_ubatch:
        got = [r.get("input_tokens") for r in records
               if r["case"] == "ceiling" and r.get("params", {}).get("reported") == "n_ubatch"]
        check["ubatch_ok"] = bool(got) and got[0] == cfg.expect_ubatch
        if not check["ubatch_ok"]:
            log(f"!! n_ubatch mismatch: reported {got or 'not probed'}, expected {cfg.expect_ubatch}")

    meta = {"label": cfg.label, "started": started, "url": cfg.url, "reps": cfg.reps,
            "machine": cfg.machine, "stack": cfg.stack, "revision": cfg.revision, "notes": cfg.notes,
            "identity_check": check,
            "max_per_question_tokens": cfg.max_per_question_tokens, "text_version": TEXT_VERSION,
            "identity": identity, "crashes": ep.crashes, "suite": cfg.suite,
            "n_records": len(records)}
    os.makedirs(cfg.out_dir, exist_ok=True)
    stamp = started.replace(":", "").replace("-", "").replace("T", "-")
    jpath = os.path.join(cfg.out_dir, f"{stamp}-{cfg.label}.json")
    mpath = os.path.join(cfg.out_dir, f"{stamp}-{cfg.label}.md")
    with open(jpath, "w") as f:
        json.dump({"meta": meta, "records": records}, f, indent=2)
    with open(mpath, "w") as f:
        f.write(to_md(meta, records))
    with open(os.path.join(cfg.out_dir, "index.jsonl"), "a") as f:
        f.write(json.dumps({"started": started, "label": cfg.label, "machine": cfg.machine,
                            "stack": cfg.stack, "revision": cfg.revision,
                            "model": identity["model"], "build_info": identity["build_info"],
                            "identity": identity, "crashes": len(ep.crashes),
                            "json": jpath, "md": mpath}) + "\n")
    log(f"\nwrote {jpath}\nwrote {mpath}")
    if ep.crashes:
        log(f"NOTE: the endpoint died {len(ep.crashes)} time(s) during this run")


if __name__ == "__main__":
    main()
