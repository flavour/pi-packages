def c_identity(ep, cfg):
    rows = []
    for p in ("/health", "/props", "/v1/models", "/slots"):
        st, body = ep.get(p)
        rows.append({"case": "identity", "params": {"path": p}, "status": st,
                     "body": body if isinstance(body, (dict, list)) else str(body)[:300]})
    r = ep.call({"state": TOY_STATE, "questions": {"a": noul("reversible")}})
    rows.append({"case": "identity", "params": {"path": "response.model"},
                 "model": r["body"].get("model") if r["body"] else None,
                 "build_info": next((b["body"].get("build_info") for b in rows
                                     if b["params"]["path"] == "/props" and isinstance(b["body"], dict)), None),
                 "kind": r["kind"], "error": r["error"]})
    return rows


def c_token_accounting(ep, cfg):
    """Is the state re-processed per question? The headline for state sharing."""
    rows = []
    for n in (1, 2, 4, 8, 12):
        runs = timed(ep, {"state": TOY_STATE, "questions": generic(n)}, 1)
        s = summarize(runs)
        rows.append({"case": "token_accounting", "params": {"n": n, "state": "toy"},
                     "input_tokens": s["input_tokens"],
                     "tokens_per_question": round(s["input_tokens"] / n, 1) if s["input_tokens"] else None,
                     "latency": s["median_latency"], "kind": s and runs[0]["kind"], "errors": s["errors"]})
    for pads in (15,):
        st = TOY_STATE + PAD * pads
        for n in (1, 4):
            runs = timed(ep, {"state": st, "questions": generic(n)}, 1)
            s = summarize(runs)
            rows.append({"case": "token_accounting", "params": {"n": n, "pads": pads},
                         "input_tokens": s["input_tokens"],
                         "tokens_per_question": round(s["input_tokens"] / n, 1) if s["input_tokens"] else None,
                         "latency": s["median_latency"], "kind": runs[0]["kind"], "errors": s["errors"]})
    return rows


def c_latency_vs_n(ep, cfg):
    import random
    res, toks = {}, {}
    for _ in range(cfg.reps):
        order = [1, 2, 3, 4, 6, 8, 12]
        random.shuffle(order)
        for n in order:
            runs = timed(ep, {"state": TOY_STATE, "questions": generic(n)}, 1)
            s = summarize(runs)
            if s["median_latency"]:
                res.setdefault(n, []).append(s["median_latency"]); toks[n] = s["input_tokens"]
            else:
                res.setdefault(n, []).append(None)
    rows = []
    for n in sorted(res):
        v = [x for x in res[n] if x]
        rows.append({"case": "latency_vs_n", "params": {"n": n}, "median": med(v),
                     "min": round(min(v), 4) if v else None, "max": round(max(v), 4) if v else None,
                     "tokens_per_question": round(toks[n] / n, 1) if n in toks else None})
    ns = [n for n in sorted(res) if [x for x in res[n] if x]]
    for i in range(1, len(ns)):
        a = statistics.median(res[ns[i - 1]]); b = statistics.median(res[ns[i]])
        rows.append({"case": "latency_vs_n_marginal", "params": {"from": ns[i - 1], "to": ns[i]},
                     "ms_per_question": round((b - a) / (ns[i] - ns[i - 1]) * 1000, 1)})
    return rows


