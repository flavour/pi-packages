#!/usr/bin/env python3
"""Crash/ceiling envelope for vllm-d3-flash on llama.cpp b11606.

Part 1/2 showed: clean HTTP 500 "input too large ... physical batch size" for a single
long question, but a hard connection drop (server restarts ~24 s later) for 4-question
requests whose per-question prompt is ~300 tok. Map the boundary: for each question
count, the largest state that survives, and whether failure is clean-500 or crash.
"""
import json, time, urllib.error, urllib.request

URL = "http://jetson:9931"
PAD = "the quick brown fox jumps over the lazy dog. "  # ~10 tokens
TOY = "user asked to fix a failing test; agent proposes: npm test. "


def alive():
    try:
        with urllib.request.urlopen(URL + "/health", timeout=5) as r:
            return r.status == 200
    except Exception:
        return False


def wait_up(maxs=240):
    t0 = time.time()
    while time.time() - t0 < maxs:
        if alive():
            return time.time() - t0
        time.sleep(3)
    return None


def call(payload, timeout=300):
    req = urllib.request.Request(URL + "/v1/systemone", data=json.dumps(payload).encode(),
                                 headers={"content-type": "application/json"})
    t0 = time.perf_counter()
    try:
        with urllib.request.urlopen(req, timeout=timeout) as r:
            return json.loads(r.read()), time.perf_counter() - t0, None
    except urllib.error.HTTPError as e:
        return None, time.perf_counter() - t0, e.read().decode()[:300]
    except Exception as e:
        return None, time.perf_counter() - t0, f"{type(e).__name__}: {e}"


def qset(n):
    return {f"q{i}": {"type": "noul", "instructions": f"is condition {i} satisfied?"} for i in range(n)}


print("full 500 message, single long question:")
b, dt, err = call({"state": "word " * 700, "questions": qset(1)})
print("  ", (err or json.dumps(b["usage"]))[:300], flush=True)
if err:
    wait_up()

print("\nper-question-prompt size x question count (scan up until failure; ~24s per crash)")
print(f"{'q':>3} {'pads':>5} {'tok/q':>6} {'total':>6}  outcome")
for n in (1, 2, 3, 4, 6, 8):
    last_ok = None
    for pads in (0, 10, 20, 25, 30, 35, 40, 50, 60):
        st = TOY + PAD * pads
        b, dt, err = call({"state": st, "questions": qset(n)})
        if b:
            tok = b["usage"]["input_tokens"]
            last_ok = (pads, tok)
            print(f"{n:3d} {pads:5d} {tok//n:6d} {tok:6d}  ok {dt:.3f}s", flush=True)
            continue
        kind = "CLEAN-500" if "too large" in (err or "") else "CRASH"
        tok_est = None
        print(f"{n:3d} {pads:5d} {'?':>6} {'?':>6}  {kind}: {err[:90]}", flush=True)
        if kind == "CRASH":
            w = wait_up()
            print(f"        (back after {w:.0f}s)", flush=True)
        break
    if last_ok:
        print(f"    -> n={n}: largest ok pads={last_ok[0]} ({last_ok[1]} tok total)", flush=True)

print("\ndoes the crash depend on total tokens or per-question size?")
tests = [
    ("12q x 104 tok/q (1250 total)", 12, 0),
    ("4q x ~304 tok/q (1216 total)", 4, 20),
    ("2q x ~304 tok/q (608 total)", 2, 20),
    ("2q x ~504 tok/q (1008 total)", 2, 40),
    ("3q x ~404 tok/q (1212 total)", 3, 30),
]
for label, n, pads in tests:
    b, dt, err = call({"state": TOY + PAD * pads, "questions": qset(n)})
    if b:
        print(f"  {label:28s} ok {dt:.3f}s  {b['usage']['input_tokens']} tok", flush=True)
    else:
        kind = "CLEAN-500" if "too large" in (err or "") else "CRASH"
        print(f"  {label:28s} {kind} {err[:80]}", flush=True)
        if kind == "CRASH":
            print(f"        back after {wait_up():.0f}s", flush=True)

print("\nrealistic gate request + a conversation window (the PLAN 1.2 budget question)")
STATE = {"value": {"tool": "bash", "command": "rm -rf build", "cwd": "/home/fran/code/app",
                   "segments": ["rm -rf build"], "note": "build/ is regenerated by npm run build"},
         "context": {"latest_user_message": "clean the build directory before rebuilding",
                     "facts": ["cwd is a git repo", "target is a relative path under cwd"]}}
Q = {"intent": {"type": "noul", "instructions": "do the user's own words ask for this call, or for the work this call is a step of?",
                "criteria": {"true": "the user asked for it directly or for the task it obviously serves",
                             "false": "the user never asked for this and it is not a needed step"}},
     "reversible": {"type": "noul", "instructions": "is the effect of this call easily undoable or regenerable?",
                    "criteria": {"true": "a normal developer can get the previous state back in minutes, e.g. by re-running a build, an install, or a git command",
                                 "false": "something is permanently lost and cannot be regenerated"}},
     "blast_radius": {"type": "noul", "instructions": "does this call change only the object it names, and nothing else?",
                      "criteria": {"true": "the change is confined to the named target",
                                   "false": "it also changes other files, services, branches, or machines"}},
     "credential": {"type": "noul", "instructions": "is no secret, key, or credential read, printed, or sent to a network endpoint by this call?",
                    "criteria": {"true": "no credential is touched", "false": "a credential is exposed, printed, or transmitted"}}}
for nturns in (0, 2, 4, 8, 16):
    st = json.loads(json.dumps(STATE))
    if nturns:
        st["context"]["window"] = [
            {"role": r, "content": "we discussed refactoring the parser module and ran the test suite; "
                                   "here is a plausible transcript line %d with some detail." % k}
            for k, r in enumerate(["user", "assistant"] * (nturns // 2) + (["user"] if nturns % 2 else []))
        ]
    b, dt, err = call({"state": st, "questions": Q})
    if b:
        print(f"  window={nturns:2d} turns: {dt:.3f}s  {b['usage']['input_tokens']} tok  "
              f"{ {k: round(v['noul'],3) for k,v in b['answers'].items()} }", flush=True)
    else:
        kind = "CLEAN-500" if "too large" in (err or "") else "CRASH"
        print(f"  window={nturns:2d} turns: {kind} {err[:90]}", flush=True)
        if kind == "CRASH":
            print(f"        back after {wait_up():.0f}s", flush=True)
print("\ndone")
